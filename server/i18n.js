export function createTerminalTranslator(language = 'en') {
  const catalog = terminalMessages[/^es(?:[-_]|$)/i.test(language ?? '') ? 'es' : 'en'];
  return (key, values = {}) => {
    const template = Object.hasOwn(catalog, key) ? catalog[key] : key;
    return template.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
  };
}

export const t = createTerminalTranslator(process.env.JOYPAD_LANG);
